def evaluate(catalog, profiles=None):
    ids = {p['id'] for p in catalog}
    report = []
    for story, topic, expected in CASES:
        expected = [i for i in expected if i in ids]
        profile = {'story_summary': [story], 'needs': [topic], 'priority': topic, 'town': 'unknown'}
        if profiles is not None:
            profile.update(profiles[story])
        with patch.object(embeddings, 'configured', return_value=False):
            lexical = engine.retrieve(catalog, profile)
        started = time.monotonic()
        hybrid = engine.retrieve(catalog, profile)
        row = {'story': story, 'search_terms': profile.get('search_terms', []),
               'expected_ids': expected, 'seconds': round(time.monotonic() - started, 3)}
        for name, ranked in (('lexical', lexical), ('hybrid', hybrid)):
            order = {p['id']: i + 1 for i, p in enumerate(ranked)}
            row[name] = {'expected_ranks': {i: order[i] for i in expected},
                         'hits_at_18': sum(order[i] <= 18 for i in expected),
                         'top_5': [{'id': p['id'], 'title': p['title']} for p in ranked[:5]]}
        report.append(row)
    return {'model': embeddings.settings()[2], 'policies': len(catalog), 'cases': report,
            'total_targets': sum(len(r['expected_ids']) for r in report),
            'lexical_hits_at_18': sum(r['lexical']['hits_at_18'] for r in report),
            'hybrid_hits_at_18': sum(r['hybrid']['hits_at_18'] for r in report)}


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('catalog')
    parser.add_argument('--output', required=True)
    parser.add_argument('--env-file', help='Server-only encoder settings; never printed')
    parser.add_argument('--profiles', help='Synthetic profiles generated by the actual story/intake pipeline')
    args = parser.parse_args()
    if args.env_file:
        for line in Path(args.env_file).read_text().splitlines():
            if '=' in line:
                key, value = line.split('=', 1)
                if key.startswith('EMBEDDING_'):
                    os.environ[key] = value
    if not embeddings.configured():
        raise RuntimeError('Encoder settings are required for evaluation')
    catalog = json.loads(Path(args.catalog).read_text(encoding='utf-8'))
    print('Indexing public policies:', len(catalog), flush=True)
    embeddings.index_catalog(catalog)
    profiles = json.loads(Path(args.profiles).read_text()) if args.profiles else None
    result = evaluate(catalog, profiles)
    Path(args.output).write_text(json.dumps(result, ensure_ascii=False, indent=2), encoding='utf-8')
    print({k: v for k, v in result.items() if k != 'cases'}, flush=True)


if __name__ == '__main__':
    main()
